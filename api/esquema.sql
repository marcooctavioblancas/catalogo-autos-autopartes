CREATE TABLE IF NOT EXISTS usuarios (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL,
  correo VARCHAR(160) NOT NULL UNIQUE,
  clave VARCHAR(255) NOT NULL,
  rol ENUM('comprador','dueno') NOT NULL DEFAULT 'comprador',
  verificado TINYINT(1) NOT NULL DEFAULT 0,
  token CHAR(64) NULL,
  token_expira DATETIME NULL,
  creado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS vehiculos (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  tipo ENUM('seminuevo','autopartes') NOT NULL,
  marca VARCHAR(60) NOT NULL,
  modelo VARCHAR(60) NOT NULL,
  version VARCHAR(60) NOT NULL DEFAULT '',
  anio SMALLINT UNSIGNED NOT NULL,
  precio INT UNSIGNED NULL,
  km INT UNSIGNED NULL,
  transmision VARCHAR(60) NOT NULL DEFAULT '',
  combustible VARCHAR(40) NOT NULL DEFAULT '',
  motor VARCHAR(60) NOT NULL DEFAULT '',
  color VARCHAR(40) NOT NULL DEFAULT '',
  puertas TINYINT UNSIGNED NULL,
  duenos VARCHAR(40) NOT NULL DEFAULT '',
  descripcion TEXT NULL,
  estado ENUM('disponible','apartado','vendido') NOT NULL DEFAULT 'disponible',
  creado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS fotos (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  vehiculo_id INT UNSIGNED NOT NULL,
  archivo VARCHAR(80) NOT NULL,
  vista VARCHAR(30) NOT NULL DEFAULT '',
  portada TINYINT(1) NOT NULL DEFAULT 0,
  FOREIGN KEY (vehiculo_id) REFERENCES vehiculos(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS partes (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  vehiculo_id INT UNSIGNED NOT NULL,
  nombre VARCHAR(120) NOT NULL,
  categoria VARCHAR(60) NOT NULL DEFAULT '',
  codigo VARCHAR(30) NOT NULL DEFAULT '',
  precio INT UNSIGNED NOT NULL DEFAULT 0,
  estado ENUM('existencia','agotado') NOT NULL DEFAULT 'existencia',
  FOREIGN KEY (vehiculo_id) REFERENCES vehiculos(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS tickets (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  folio VARCHAR(12) NOT NULL UNIQUE,
  usuario_id INT UNSIGNED NULL,
  nombre VARCHAR(80) NOT NULL DEFAULT '',
  total INT UNSIGNED NOT NULL DEFAULT 0,
  atendido TINYINT(1) NOT NULL DEFAULT 0,
  creado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ticket_items (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ticket_id INT UNSIGNED NOT NULL,
  descripcion VARCHAR(255) NOT NULL,
  precio INT UNSIGNED NOT NULL DEFAULT 0,
  FOREIGN KEY (ticket_id) REFERENCES tickets(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS favoritos (
  usuario_id INT UNSIGNED NOT NULL,
  vehiculo_id INT UNSIGNED NOT NULL,
  PRIMARY KEY (usuario_id, vehiculo_id),
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE,
  FOREIGN KEY (vehiculo_id) REFERENCES vehiculos(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ajustes (
  clave VARCHAR(40) PRIMARY KEY,
  valor VARCHAR(255) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS vistos (
  usuario_id INT UNSIGNED NOT NULL,
  vehiculo_id INT UNSIGNED NOT NULL,
  visto DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (usuario_id, vehiculo_id),
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE,
  FOREIGN KEY (vehiculo_id) REFERENCES vehiculos(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
